CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255),
    telefone VARCHAR(255),
    perfil VARCHAR(255) NOT NULL CHECK (perfil IN ('GERADOR', 'FRETEIRO')),
    data_cadastro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE perfis_freteiro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id),
    tipo_veiculo VARCHAR(255) NOT NULL,
    modelo_veiculo VARCHAR(255) NOT NULL,
    placa VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE locais_descarte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(2000),
    endereco VARCHAR(255) NOT NULL,
    bairro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(255) NOT NULL UNIQUE,
    gerador_id BIGINT NOT NULL REFERENCES usuarios(id),
    freteiro_id BIGINT REFERENCES usuarios(id),
    quantidade_sacos INTEGER NOT NULL CHECK (quantidade_sacos BETWEEN 1 AND 50),
    volume_estimado NUMERIC(7, 2) NOT NULL,
    faixa_preco VARCHAR(255) CHECK (faixa_preco IN ('P', 'M', 'G')),
    valor_total NUMERIC(10, 2) NOT NULL,
    valor_repasse NUMERIC(10, 2) NOT NULL,
    taxa_eco_obra NUMERIC(10, 2) NOT NULL,
    endereco_coleta VARCHAR(255) NOT NULL,
    bairro VARCHAR(255) NOT NULL,
    foto_entulho VARCHAR(2000),
    foto_descarga VARCHAR(2000),
    local_descarte_id BIGINT REFERENCES locais_descarte(id),
    status VARCHAR(255) NOT NULL CHECK (status IN ('PENDENTE', 'ACEITO', 'CONCLUIDO')),
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_aceite TIMESTAMP WITH TIME ZONE,
    data_conclusao TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_pedidos_status_freteiro ON pedidos (status, freteiro_id);
CREATE INDEX idx_pedidos_gerador_data ON pedidos (gerador_id, data_criacao DESC);
CREATE INDEX idx_pedidos_freteiro_data ON pedidos (freteiro_id, data_criacao DESC);
CREATE INDEX idx_locais_descarte_ativos ON locais_descarte (ativo);
